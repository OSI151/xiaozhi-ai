#pragma once

#include <cstdint>

// 播放通道的瞬时音量包络（0-255），由 AudioService 在把 PCM 交给 codec
// 之前算出来。给灯效这类「跟着声音动」的消费方用。
//
// 只反映「设备正在放出来的声音」，麦克风输入不在这里 —— 所以没人说话时
// 它天然是 0，不需要额外的状态判断。
void SetPlaybackLevel(uint8_t level);

// 读最近一次算出来的值。没有新数据时不会自己衰减（衰减由消费方做），
// 这样不同刷新率的两边不需要互相迁就。
//
// 但超过 120ms 没有新值会直接返回 0：播放循环停下来之后没人来写 0，
// 不做过期判断的话最后一句的音量会一直留着，灯就灭不下去。
uint8_t GetPlaybackLevel();
